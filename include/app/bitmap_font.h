// The glyph for a character; lowercase maps to capitals, unknown to '?'.
inline const Glyph& glyphFor(char character) {
    if (character >= 'a' && character <= 'z') {
        character = static_cast<char>(character - 'a' + 'A');
    }

    int count = 0;
    const Glyph* glyphs = glyphTable(count);
    const Glyph* fallback = &glyphs[0];

    for (int i = 0; i < count; i++) {
        if (glyphs[i].character == character) {
            return glyphs[i];
        }

        if (glyphs[i].character == '?') {
            fallback = &glyphs[i];
        }
    }

    return *fallback;
}

// Width in pixels of one line of text at the given scale.
inline int textWidth(const std::string& text, int scale = 1) {
    if (text.empty()) {
        return 0;
    }

    return static_cast<int>(text.size()) * (GLYPH_WIDTH + GLYPH_SPACING) * scale
           - GLYPH_SPACING * scale;
}

inline int lineHeight(int scale = 1) {
    return (GLYPH_HEIGHT + LINE_SPACING) * scale;
}

// Draws one line of text with its top-left corner at (x, y). Each font
// pixel becomes a scale x scale block. Returns the number of pixels set.
inline int drawText(RasterCanvas& canvas, int x, int y, const std::string& text,
                    const Color& color, int scale = 1) {
    int drawn = 0;
    int penX = x;

    for (char character : text) {
        const Glyph& glyph = glyphFor(character);

        for (int row = 0; row < GLYPH_HEIGHT; row++) {
            for (int column = 0; column < GLYPH_WIDTH; column++) {
                if (glyph.rows[row][column] != '#') {
                    continue;
                }

                for (int dy = 0; dy < scale; dy++) {
                    for (int dx = 0; dx < scale; dx++) {
                        int px = penX + column * scale + dx;
                        int py = y + row * scale + dy;

                        if (canvas.contains(px, py)) {
                            canvas.setPixel(px, py, color);
                            drawn++;
                        }
                    }
                }
            }
        }

        penX += (GLYPH_WIDTH + GLYPH_SPACING) * scale;
    }

    return drawn;
}

